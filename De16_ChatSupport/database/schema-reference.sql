CREATE TABLE "Participants" (
  "Id" uuid PRIMARY KEY,
  "DisplayName" varchar(100) NOT NULL,
  "Role" varchar(20) NOT NULL,                -- Customer | Agent
  "Email" varchar(200),
  "Username" varchar(50),
  "PasswordHash" varchar(300),
  "CreatedAt" timestamptz NOT NULL
);
CREATE UNIQUE INDEX "IX_Participants_Username" ON "Participants" ("Username");

CREATE TABLE "Conversations" (
  "Id" uuid PRIMARY KEY,
  "Topic" varchar(200) NOT NULL,
  "CustomerId" uuid NOT NULL REFERENCES "Participants" ("Id") ON DELETE RESTRICT,
  "AgentId" uuid NULL REFERENCES "Participants" ("Id") ON DELETE RESTRICT,
  "Status" varchar(20) NOT NULL,              -- Waiting | Active | Closed
  "CreatedAt" timestamptz NOT NULL,
  "AcceptedAt" timestamptz NULL,
  "ClosedAt" timestamptz NULL,
  "ClosedById" uuid NULL,
  "LastSequence" bigint NOT NULL,
  "MessageCount" integer NOT NULL,
  "LastMessageAt" timestamptz NULL,
  "HistorySyncedAt" timestamptz NULL
);
CREATE INDEX "IX_Conversations_Status_CreatedAt" ON "Conversations" ("Status", "CreatedAt");
CREATE INDEX "IX_Conversations_AgentId" ON "Conversations" ("AgentId");
CREATE INDEX "IX_Conversations_CustomerId" ON "Conversations" ("CustomerId");

CREATE TABLE "Messages" (
  "Id" uuid PRIMARY KEY,
  "ConversationId" uuid NOT NULL REFERENCES "Conversations" ("Id") ON DELETE RESTRICT,
  "SenderId" uuid NOT NULL REFERENCES "Participants" ("Id") ON DELETE RESTRICT,
  "Sequence" bigint NOT NULL,
  "Content" varchar(2000) NOT NULL,
  "SentAt" timestamptz NOT NULL,
  "StoredAt" timestamptz NOT NULL
);
CREATE UNIQUE INDEX "IX_Messages_ConversationId_Sequence" ON "Messages" ("ConversationId", "Sequence");
CREATE INDEX "IX_Messages_ConversationId_SentAt" ON "Messages" ("ConversationId", "SentAt");
CREATE INDEX "IX_Messages_SenderId" ON "Messages" ("SenderId");

CREATE TABLE "OutboxEvents" (
  "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "EventId" uuid NOT NULL,
  "EventType" varchar(100) NOT NULL,          -- message.sent | conversation.closed (= routing key)
  "ConversationId" uuid NOT NULL,
  "Payload" text NOT NULL,
  "CreatedAt" timestamptz NOT NULL,
  "PublishedAt" timestamptz NULL,
  "Attempts" integer NOT NULL,
  "LastError" varchar(1000) NULL
);
CREATE UNIQUE INDEX "IX_OutboxEvents_EventId" ON "OutboxEvents" ("EventId");
CREATE INDEX "IX_OutboxEvents_Pending" ON "OutboxEvents" ("Id") WHERE "PublishedAt" IS NULL;
CREATE INDEX "IX_OutboxEvents_ConversationId_EventType" ON "OutboxEvents" ("ConversationId", "EventType");
